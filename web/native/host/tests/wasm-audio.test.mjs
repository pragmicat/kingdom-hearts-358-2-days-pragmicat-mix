import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {attachDaysAudio} from '../browser-audio.mjs';
import {FakeAudioContext,FakeDocument} from './fake-audio.mjs';
const {default:createModule}=await import(pathToFileURL(process.argv[2]).href);
const module=await createModule();
const audio=attachDaysAudio(module,{AudioContextClass:FakeAudioContext,documentObject:new FakeDocument()});
try {
  module._days_test_audio_start();
  assert.equal(module._days_test_audio_exact(),1);
  module._days_test_emit_mixer(1);
  assert.equal(FakeAudioContext.instances.length,0,'real native PCM cannot create a WebAudio context');
  await audio.resume();
  const context=FakeAudioContext.instances.at(-1);
  module._days_test_emit_mixer(1);
  assert.equal(context.buffers.length,1);
  let buffer=context.buffers.at(-1);
  assert.equal(buffer.rate,32728);
  assert.equal(buffer.getChannelData(0)[0],0.5);
  assert.equal(buffer.getChannelData(1)[0],-0.5);
  const packetCount=context.buffers.length;
  module._days_test_emit_mixer(1025);
  assert.deepEqual(context.buffers.slice(packetCount).map(value=>value.frames),[512,512,1]);
  const count=context.buffers.length;
  module._days_test_audio_invalid();assert.equal(context.buffers.length,count);
  module._days_test_audio_pause(1);module._days_test_emit_mixer(1);assert.equal(context.buffers.length,count);
  module._days_test_audio_pause(0);module._days_test_emit_mixer(1);assert.equal(context.buffers.length,count+1);
  module._days_test_audio_mute(1);module._days_test_emit_mixer(1);assert.equal(context.buffers.length,count+1);
  module._days_test_audio_mute(0);
  module._days_test_emit_float();buffer=context.buffers.at(-1);
  assert.equal(buffer.rate,48000);assert.equal(buffer.getChannelData(0)[0],0.25);
  assert.equal(buffer.getChannelData(1)[0],-0.5);assert.equal(buffer.getChannelData(0)[1],1);assert.equal(buffer.getChannelData(1)[1],-1);
  const old=module.HEAPU8.buffer;const allocation=module._malloc(40*1024*1024);
  assert(allocation && module.HEAPU8.buffer!==old,'test must really grow Wasm linear memory');
  module._days_test_emit_mixer(1);assert.equal(context.buffers.at(-1).getChannelData(0)[0],0.5);
  module._free(allocation);
  await module.ccall('days_test_audio_fiber',null,[],[],{async:true});
  assert.equal(module._days_test_audio_fiber_completed(),1,'sound pump must run while an actual Days game fiber is suspended');
  await new Promise(resolve=>setTimeout(resolve,20));
  assert(module._days_test_audio_advances()>0 && module._days_test_audio_cycle()>0,'cooperative timer calls real bridge API at DS clock cycles');
  module._days_web_audio_stop();
  const advances=module._days_test_audio_advances();
  await new Promise(resolve=>setTimeout(resolve,8));
  assert.equal(module._days_test_audio_advances(),advances,'closing stops the cooperative service');
  console.log('Actual upstream DS mixer → Wasm host PCM → JS WebAudio sink passed; exactrate/chunking/pause/mute/memorygrowth/bridgepump/stop passed');
} finally {module._days_web_audio_stop();await audio.dispose();}

let exitStatus;
const ending = await createModule({onExit: status => { exitStatus = status; }});
assert.throws(() => ending._days_test_audio_exit(), error => error.status === 7);
assert.equal(exitStatus, 7, 'An active audio pump must not suppress native exit');
await new Promise(resolve => setTimeout(resolve, 8));
assert.equal(ending.daysAudioTimer, undefined, 'Native exit releases the audio interval');
process.exitCode = 0;
